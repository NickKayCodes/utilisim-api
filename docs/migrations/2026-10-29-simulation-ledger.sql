-- 2026-10-29 — Simulation ledger (CURRENT_PLAN_DESIGN §6)
--
-- Status: prepared for the PostgreSQL database. Flyway is NOT enabled yet in this
-- project; `ddl-auto=update` still creates the entities. This script is the reviewed
-- DDL to apply (and the basis for the Flyway baseline that follows).
--
-- Run once, inside a transaction, after taking a backup:
--   psql -v ON_ERROR_STOP=1 -f 2026-10-29-simulation-ledger.sql
--
-- Money is numeric(12,2); APR is numeric(7,4); row identifiers are bigint.

BEGIN;

-- ---------------------------------------------------------------- tome_ledger
ALTER TABLE tome_ledger
    ADD COLUMN IF NOT EXISTS current_payment numeric(12,2);

ALTER TABLE tome_ledger
    ALTER COLUMN current_balance      TYPE numeric(12,2) USING current_balance::numeric(12,2),
    ALTER COLUMN minimum_debt_payment TYPE numeric(12,2) USING minimum_debt_payment::numeric(12,2),
    ALTER COLUMN credit_limit         TYPE numeric(12,2) USING credit_limit::numeric(12,2),
    ALTER COLUMN current_payment      TYPE numeric(12,2) USING current_payment::numeric(12,2),
    ALTER COLUMN apr                  TYPE numeric(7,4)  USING apr::numeric(7,4),
    ALTER COLUMN estimated_apr        TYPE numeric(7,4)  USING estimated_apr::numeric(7,4);

-- No backfill: NULL current_payment means "same as the minimum" and is resolved
-- into simulation_run_debt when a run is created.

-- ------------------------------------------------------------- simulation_run
ALTER TABLE simulation_run
    ALTER COLUMN id TYPE bigint;

ALTER TABLE simulation_run
    ADD COLUMN IF NOT EXISTS plan_type varchar(16),
    ADD COLUMN IF NOT EXISTS termination_reason varchar(24),
    ADD COLUMN IF NOT EXISTS comparison_group_id uuid,
    ADD COLUMN IF NOT EXISTS start_month date,
    ADD COLUMN IF NOT EXISTS horizon_months integer,
    ADD COLUMN IF NOT EXISTS extra_payment numeric(12,2),
    ADD COLUMN IF NOT EXISTS lump_sum_payment numeric(12,2),
    ADD COLUMN IF NOT EXISTS lump_sum_month integer,
    ADD COLUMN IF NOT EXISTS total_interest numeric(12,2),
    ADD COLUMN IF NOT EXISTS total_paid numeric(12,2),
    ADD COLUMN IF NOT EXISTS final_balance numeric(12,2),
    ADD COLUMN IF NOT EXISTS months_to_payoff integer,
    ADD COLUMN IF NOT EXISTS payoff_date timestamptz,
    ADD COLUMN IF NOT EXISTS peak_utilization numeric(6,2);

CREATE INDEX IF NOT EXISTS idx_simulation_run_user
    ON simulation_run (user_id);
CREATE INDEX IF NOT EXISTS idx_simulation_run_group
    ON simulation_run (comparison_group_id);

-- ---------------------------------------------------------- simulation_run_debt
-- Immutable input snapshot: makes a stored comparison reproducible after the
-- account is edited or deleted.
CREATE TABLE IF NOT EXISTS simulation_run_debt (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id            bigint NOT NULL REFERENCES simulation_run (id) ON DELETE CASCADE,
    tome_id           varchar(255) NOT NULL,
    account_name      varchar(255),
    starting_balance  numeric(12,2) NOT NULL,
    apr               numeric(7,4)  NOT NULL,
    minimum_payment   numeric(12,2) NOT NULL,
    current_payment   numeric(12,2) NOT NULL,
    credit_limit      numeric(12,2),
    CONSTRAINT uq_simulation_run_debt UNIQUE (run_id, tome_id)
);

-- ------------------------------------------------------------ simulation_month
CREATE TABLE IF NOT EXISTS simulation_month (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                    bigint NOT NULL REFERENCES simulation_run (id) ON DELETE CASCADE,
    month_index               integer NOT NULL,
    month_label               varchar(7),
    period_start              date,
    starting_balance          numeric(12,2) NOT NULL,
    monthly_interest          numeric(12,2) NOT NULL,
    minimum_due               numeric(12,2) NOT NULL,
    actual_payment            numeric(12,2) NOT NULL,
    extra_payment             numeric(12,2) NOT NULL,
    lump_sum_applied          numeric(12,2) NOT NULL,
    remaining_balance         numeric(12,2) NOT NULL,
    utilization_pct           numeric(6,2),
    interest_paid             numeric(12,2) NOT NULL,
    amount_to_cover_interest  numeric(12,2) NOT NULL,
    CONSTRAINT uq_simulation_month UNIQUE (run_id, month_index)
);

-- ------------------------------------------------------- simulation_month_debt
CREATE TABLE IF NOT EXISTS simulation_month_debt (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                    bigint NOT NULL REFERENCES simulation_run (id) ON DELETE CASCADE,
    month_index               integer NOT NULL,
    tome_id                   varchar(255) NOT NULL,
    account_name              varchar(255),
    starting_balance          numeric(12,2) NOT NULL,
    monthly_interest          numeric(12,2) NOT NULL,
    minimum_due               numeric(12,2) NOT NULL,
    actual_payment            numeric(12,2) NOT NULL,
    extra_payment             numeric(12,2) NOT NULL,
    lump_sum_applied          numeric(12,2) NOT NULL,
    remaining_balance         numeric(12,2) NOT NULL,
    utilization_pct           numeric(6,2),
    interest_paid             numeric(12,2) NOT NULL,
    amount_to_cover_interest  numeric(12,2) NOT NULL,
    CONSTRAINT uq_simulation_month_debt UNIQUE (run_id, month_index, tome_id)
);

CREATE INDEX IF NOT EXISTS idx_simulation_month_run
    ON simulation_month (run_id, month_index);
CREATE INDEX IF NOT EXISTS idx_simulation_month_debt_run
    ON simulation_month_debt (run_id, month_index);

COMMIT;

